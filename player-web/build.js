const esbuild = require('esbuild');
const fs = require('fs');
const path = require('path');

async function build() {
  console.log('Building Path Hub Player Layer...');

  // 1. Bundle TypeScript to single JS (IIFE format)
  await esbuild.build({
    entryPoints: [path.join(__dirname, 'src/index.ts')],
    bundle: true,
    minify: false, // Keep readable for debugging; 60fps CSS/DOM performance unaffected
    sourcemap: false,
    format: 'iife',
    globalName: 'PathHubPlayerLayer',
    outfile: path.join(__dirname, 'dist/player.js'),
    target: ['es2020']
  });

  // 2. Process / bundle CSS
  const cssSourcePath = path.join(__dirname, 'src/styles/player.css');
  const cssDistPath = path.join(__dirname, 'dist/player.css');
  if (fs.existsSync(cssSourcePath)) {
    fs.copyFileSync(cssSourcePath, cssDistPath);
  }

  // 3. Read generated outputs
  const jsContent = fs.readFileSync(path.join(__dirname, 'dist/player.js'), 'utf8');
  const cssContent = fs.existsSync(cssDistPath) ? fs.readFileSync(cssDistPath, 'utf8') : '';

  // 4. Copy to iOS Resources
  const iosResourcesDir = path.join(__dirname, '../ios/Sources/PathHub/Resources');
  if (!fs.existsSync(iosResourcesDir)) {
    fs.mkdirSync(iosResourcesDir, { recursive: true });
  }

  fs.writeFileSync(path.join(iosResourcesDir, 'player.js'), jsContent);
  fs.writeFileSync(path.join(iosResourcesDir, 'player.css'), cssContent);

  // 5. Generate Swift static constants for bulletproof zero-IO injection in xtool
  const escapedJS = JSON.stringify(jsContent);
  const escapedCSS = JSON.stringify(cssContent);
  const swiftContent = `// Auto-generated by player-web/build.js - DO NOT EDIT MANUALLY
import Foundation

public enum InjectedScripts {
    public static let playerJS: String = ${escapedJS}
    public static let playerCSS: String = ${escapedCSS}
}
`;
  fs.writeFileSync(path.join(iosResourcesDir, 'InjectedScripts.swift'), swiftContent);

  // 6. Copy to Android Assets (when directory exists)
  const androidAssetsDir = path.join(__dirname, '../android/app/src/main/assets');
  if (fs.existsSync(androidAssetsDir)) {
    fs.writeFileSync(path.join(androidAssetsDir, 'player.js'), jsContent);
    fs.writeFileSync(path.join(androidAssetsDir, 'player.css'), cssContent);
  }

  console.log('✓ Successfully bundled player.js and player.css, updated iOS resources and Swift constants.');
}

build().catch((err) => {
  console.error('Build error:', err);
  process.exit(1);
});
